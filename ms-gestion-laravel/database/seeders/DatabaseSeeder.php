    /** Inserta por lotes; insertOrIgnore permite volver a correr el seeder sin duplicar. */
    private function bulk(string $table, array $columns, array $rows): void
    {
        foreach (array_chunk($rows, 500) as $chunk) {
            DB::table($table)->insertOrIgnore(array_map(fn ($r) => array_combine($columns, $r), $chunk));
        }
    }

    private function syncSequence(string $table): void
    {
        DB::statement("SELECT setval(pg_get_serial_sequence('{$table}', 'id'), COALESCE((SELECT MAX(id) FROM {$table}), 1))");
    }
